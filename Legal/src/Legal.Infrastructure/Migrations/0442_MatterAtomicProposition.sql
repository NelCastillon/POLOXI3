SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;

-- ============================================================================
-- 0442: Per-matter Atomic Propositions (Table/API/UI). Mirrors 0441 (Evidence Type scope) one level down:
--   one row per Decision Matter x Domain Pack parent L2 target (Evidence Type / Concept) x LLM-generated
--   atomic proposition (L3 and deeper). Stores every LLM-returned value for the proposition, the worker
--   (parallel batch slot / recovery) that produced it, and the call provenance (model, provider, tokens,
--   duration, level, batch, attempt). Attorneys may override the scope status; USER decisions are
--   authoritative and never overwritten by the system. Rows are never deleted by the pipeline.
--   Wide2 reads this table after L3 generation: OUT_OF_SCOPE propositions are marked eliminated for the
--   run (MATTER_SCOPE_OUT) and do not drive deeper narrowing or scoring.
-- ============================================================================
BEGIN TRANSACTION;

DECLARE @Now DATETIME2=SYSUTCDATETIME();

-- ── Lookup: proposition scope status ─────────────────────────────────────────────────────────────────
IF OBJECT_ID(N'POLOXI.Legal_MatterAtomicPropositionStatus',N'U') IS NULL
BEGIN
	CREATE TABLE POLOXI.Legal_MatterAtomicPropositionStatus
	(
		MatterAtomicPropositionStatusId UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Legal_MatterAtomicPropositionStatus PRIMARY KEY DEFAULT NEWID(),
		TenantId UNIQUEIDENTIFIER NULL,
		StatusCode NVARCHAR(40) NOT NULL,
		Name NVARCHAR(120) NOT NULL,
		Description NVARCHAR(600) NULL,
		ParticipatesInNarrowing BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionStatus_Narrow DEFAULT 1,
		SortOrder INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionStatus_Sort DEFAULT 0,
		IsActive BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionStatus_Active DEFAULT 1,
		CreatedDateUtc DATETIME2 NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionStatus_Created DEFAULT SYSUTCDATETIME(),
		CreatedByUserId UNIQUEIDENTIFIER NULL,
		ModifiedDateUtc DATETIME2 NULL,
		ModifiedByUserId UNIQUEIDENTIFIER NULL,
		IsDeleted BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionStatus_IsDeleted DEFAULT 0
	);
	CREATE UNIQUE INDEX UX_Legal_MatterAtomicPropositionStatus_Code ON POLOXI.Legal_MatterAtomicPropositionStatus(StatusCode) WHERE IsDeleted=0 AND TenantId IS NULL;
END;

MERGE POLOXI.Legal_MatterAtomicPropositionStatus AS t
USING (VALUES
	(N'IN_SCOPE',      N'In scope',       N'Proposition participates in deeper narrowing, grounding and scoring for this matter.',1,10),
	(N'OUT_OF_SCOPE',  N'Out of scope',   N'Proposition is held back for this matter: marked eliminated in each run, never deleted, can be re-included.',0,20),
	(N'PENDING_REVIEW',N'Pending review', N'Generated by the model and awaiting attorney review; participates until decided.',1,30)
) AS s(StatusCode,Name,Description,ParticipatesInNarrowing,SortOrder)
ON t.StatusCode=s.StatusCode AND t.TenantId IS NULL AND t.IsDeleted=0
WHEN NOT MATCHED THEN INSERT(TenantId,StatusCode,Name,Description,ParticipatesInNarrowing,SortOrder,IsActive,CreatedDateUtc,IsDeleted)
	VALUES(NULL,s.StatusCode,s.Name,s.Description,s.ParticipatesInNarrowing,s.SortOrder,1,@Now,0);

-- ── Lookup: decided-by ───────────────────────────────────────────────────────────────────────────────
IF OBJECT_ID(N'POLOXI.Legal_MatterAtomicPropositionDecider',N'U') IS NULL
BEGIN
	CREATE TABLE POLOXI.Legal_MatterAtomicPropositionDecider
	(
		MatterAtomicPropositionDeciderId UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Legal_MatterAtomicPropositionDecider PRIMARY KEY DEFAULT NEWID(),
		TenantId UNIQUEIDENTIFIER NULL,
		DeciderCode NVARCHAR(30) NOT NULL,
		Name NVARCHAR(120) NOT NULL,
		Description NVARCHAR(600) NULL,
		IsAuthoritative BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionDecider_Auth DEFAULT 0,
		SortOrder INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionDecider_Sort DEFAULT 0,
		IsActive BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionDecider_Active DEFAULT 1,
		CreatedDateUtc DATETIME2 NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionDecider_Created DEFAULT SYSUTCDATETIME(),
		CreatedByUserId UNIQUEIDENTIFIER NULL,
		ModifiedDateUtc DATETIME2 NULL,
		ModifiedByUserId UNIQUEIDENTIFIER NULL,
		IsDeleted BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicPropositionDecider_IsDeleted DEFAULT 0
	);
	CREATE UNIQUE INDEX UX_Legal_MatterAtomicPropositionDecider_Code ON POLOXI.Legal_MatterAtomicPropositionDecider(DeciderCode) WHERE IsDeleted=0 AND TenantId IS NULL;
END;

MERGE POLOXI.Legal_MatterAtomicPropositionDecider AS t
USING (VALUES
	(N'LLM',  N'LLM generated',     N'Generated by the Wide2 atomic-proposition model pass (a parallel worker or targeted recovery).',0,10),
	(N'USER', N'Attorney override', N'Decided by a user. Authoritative: the system never overwrites a USER decision.',1,20)
) AS s(DeciderCode,Name,Description,IsAuthoritative,SortOrder)
ON t.DeciderCode=s.DeciderCode AND t.TenantId IS NULL AND t.IsDeleted=0
WHEN NOT MATCHED THEN INSERT(TenantId,DeciderCode,Name,Description,IsAuthoritative,SortOrder,IsActive,CreatedDateUtc,IsDeleted)
	VALUES(NULL,s.DeciderCode,s.Name,s.Description,s.IsAuthoritative,s.SortOrder,1,@Now,0);

-- ── Per-matter atomic propositions ───────────────────────────────────────────────────────────────────
IF OBJECT_ID(N'POLOXI.Legal_MatterAtomicProposition',N'U') IS NULL
BEGIN
	CREATE TABLE POLOXI.Legal_MatterAtomicProposition
	(
		MatterAtomicPropositionId UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Legal_MatterAtomicProposition PRIMARY KEY,
		TenantId UNIQUEIDENTIFIER NOT NULL,
		DecisionMatterId UNIQUEIDENTIFIER NOT NULL CONSTRAINT FK_Legal_MatterAtomicProposition_Matter REFERENCES POLOXI.Legal_DecisionMatter(DecisionMatterId),
		PackCode NVARCHAR(80) NOT NULL,
		-- Parent L2 target (links to Legal_MatterEvidenceScope by matter+pack+kind+code).
		ParentTargetKindCode NVARCHAR(30) NOT NULL,   -- CONCEPT | EVIDENCE_TYPE
		ParentTargetCode NVARCHAR(240) NOT NULL,
		ParentDisplayName NVARCHAR(300) NOT NULL,
		DimensionCode NVARCHAR(120) NOT NULL,
		-- Direct parent proposition for L4+ (null for L3).
		ParentPropositionCode NVARCHAR(240) NULL,
		-- LLM-returned proposition values.
		PropositionCode NVARCHAR(240) NOT NULL,
		LevelNumber INT NOT NULL,
		DisplayName NVARCHAR(300) NOT NULL,
		Statement NVARCHAR(2000) NOT NULL,            -- interpretation / proposition text
		SearchText NVARCHAR(600) NULL,
		CapabilityCode NVARCHAR(120) NULL,
		Confidence DECIMAL(5,4) NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Conf DEFAULT 0,
		SemanticTypeCode NVARCHAR(30) NULL,           -- ALTERNATIVE | DIMENSION
		BranchRoleCode NVARCHAR(30) NULL,             -- HARD_CONSTRAINT | GUARDRAIL | PREFERENCE | CONTEXT
		ContinueNarrowing BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Continue DEFAULT 0,
		StopReason NVARCHAR(600) NULL,
		DependsOnCodes NVARCHAR(2000) NULL,           -- comma-separated validated codes
		EquivalentToCodes NVARCHAR(2000) NULL,
		AnchorCount INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Anchors DEFAULT 0,
		AnchorsJson NVARCHAR(MAX) NULL,               -- [{passageId,quote,role,pageNumber}]
		-- Worker / call provenance.
		WorkerName NVARCHAR(60) NOT NULL,             -- Worker 1..N | Recovery N
		BatchNumber INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Batch DEFAULT 0,
		AttemptNumber INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Attempt DEFAULT 1,
		BatchTierCode NVARCHAR(20) NULL,              -- TIER_ONE | TIER_A | STANDARD | RETRY
		ModelCode NVARCHAR(120) NULL,
		ProviderCode NVARCHAR(60) NULL,
		InputTokenCount INT NULL,
		OutputTokenCount INT NULL,
		DurationMs INT NULL,
		ProviderRequestId NVARCHAR(200) NULL,
		-- Scope decision.
		ScopeStatusCode NVARCHAR(40) NOT NULL,        -- Legal_MatterAtomicPropositionStatus
		DecidedByCode NVARCHAR(30) NOT NULL,          -- Legal_MatterAtomicPropositionDecider
		UserNote NVARCHAR(1000) NULL,
		GenerationCount INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_GenCount DEFAULT 1,
		LastWideBranchId UNIQUEIDENTIFIER NULL,
		LastEvaluatedExecutionId UNIQUEIDENTIFIER NULL,
		LastEvaluatedDateUtc DATETIME2 NULL,
		SortOrder INT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Sort DEFAULT 0,
		CreatedDateUtc DATETIME2 NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_Created DEFAULT SYSUTCDATETIME(),
		CreatedByUserId UNIQUEIDENTIFIER NULL,
		ModifiedDateUtc DATETIME2 NULL,
		ModifiedByUserId UNIQUEIDENTIFIER NULL,
		IsDeleted BIT NOT NULL CONSTRAINT DF_Legal_MatterAtomicProposition_IsDeleted DEFAULT 0
	);
	CREATE UNIQUE INDEX UX_Legal_MatterAtomicProposition_Code ON POLOXI.Legal_MatterAtomicProposition(TenantId,DecisionMatterId,PackCode,ParentTargetKindCode,ParentTargetCode,PropositionCode) WHERE IsDeleted=0;
	CREATE INDEX IX_Legal_MatterAtomicProposition_Matter ON POLOXI.Legal_MatterAtomicProposition(TenantId,DecisionMatterId,ScopeStatusCode) INCLUDE(ParentTargetKindCode,ParentTargetCode,LevelNumber,WorkerName,DecidedByCode,Confidence) WHERE IsDeleted=0;
	CREATE INDEX IX_Legal_MatterAtomicProposition_Parent ON POLOXI.Legal_MatterAtomicProposition(TenantId,DecisionMatterId,ParentTargetKindCode,ParentTargetCode) WHERE IsDeleted=0;
END;

COMMIT TRANSACTION;

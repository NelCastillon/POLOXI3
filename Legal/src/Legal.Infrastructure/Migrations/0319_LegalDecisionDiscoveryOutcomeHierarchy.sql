WHERE PromptCode = N'DECISION_DISCOVERY_V2'
  AND SystemPrompt NOT LIKE N'%The outcomeProposalHierarchy is a first-class discovery structure, separate from the shared legal and factual dependency hierarchy.%';

-- ── 3) First-class Outcome Proposal Hierarchy persistence: the proposed outcome-interpretation nodes
--    (O1, O1.1, …) persisted per session as a typed DISCOVERY artifact. These are NEVER evaluation
--    branches and never carry evidentiary support; POLOXI Core owns all scoring on the shared branch
--    forest. Origin links from normalized candidates are stored on the candidate row (below). ──
IF OBJECT_ID(N'POLOXI.Legal_DecisionOutcomeNode', N'U') IS NULL
CREATE TABLE POLOXI.Legal_DecisionOutcomeNode
(
	DecisionOutcomeNodeId     UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Legal_DecisionOutcomeNode PRIMARY KEY DEFAULT NEWID(),
	DecisionSessionId         UNIQUEIDENTIFIER NOT NULL,
	OutcomeNodeCode           NVARCHAR(100) NOT NULL,
	ParentOutcomeNodeCode     NVARCHAR(100) NULL,
	LevelNumber               INT NOT NULL CONSTRAINT DF_Legal_DecisionOutcomeNode_Level DEFAULT 1,
	Title                     NVARCHAR(MAX) NOT NULL,
	Description               NVARCHAR(MAX) NULL,
	DistinguishingProposition NVARCHAR(MAX) NULL,
	SortOrder                 INT NOT NULL CONSTRAINT DF_Legal_DecisionOutcomeNode_Sort DEFAULT 0,
	TenantId                  UNIQUEIDENTIFIER NOT NULL,
	CreatedDateUtc            DATETIME2 NOT NULL CONSTRAINT DF_Legal_DecisionOutcomeNode_Created DEFAULT SYSUTCDATETIME(),
	CreatedByUserId           UNIQUEIDENTIFIER NULL,
	ModifiedDateUtc           DATETIME2 NULL,
	ModifiedByUserId          UNIQUEIDENTIFIER NULL,
	IsDeleted                 BIT NOT NULL CONSTRAINT DF_Legal_DecisionOutcomeNode_IsDeleted DEFAULT 0,
	CONSTRAINT FK_Legal_DecisionOutcomeNode_Session FOREIGN KEY (DecisionSessionId) REFERENCES POLOXI.Legal_DecisionSession (DecisionSessionId)
);

IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'POLOXI.Legal_DecisionOutcomeNode') AND name = N'IX_Legal_DecisionOutcomeNode_Session')
	CREATE INDEX IX_Legal_DecisionOutcomeNode_Session ON POLOXI.Legal_DecisionOutcomeNode (DecisionSessionId) WHERE IsDeleted = 0;

-- ── Candidate origin links (§ normalization step 3): each normalized global candidate preserves the
--    originating outcome-node codes it was discovered from (e.g. "O1,O1.1"). Nullable so the legacy
--    candidate-first path and any response that omits the hierarchy are unaffected. This is DISCOVERY
--    provenance only; it never contributes evidentiary support to the candidate's authoritative score. ──
IF COL_LENGTH(N'POLOXI.Legal_DecisionCandidate', N'OriginatingOutcomeNodeIds') IS NULL
	ALTER TABLE POLOXI.Legal_DecisionCandidate ADD OriginatingOutcomeNodeIds NVARCHAR(MAX) NULL;

COMMIT TRANSACTION;

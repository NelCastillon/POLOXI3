-- POLOXI Legal R1: First-class Outcome Proposal Hierarchy for DECISION_DISCOVERY_V2, idempotent.
-- ADDITIVE enhancement to the existing branch-first discovery prompt. Astra now ALSO proposes an
-- outcomeProposalHierarchy: a first-class DISCOVERY structure of materially-distinct outcome
-- interpretations (O1, O1.1, …) that normalize into the SAME global candidate universe, with each
-- candidate carrying originatingOutcomeNodeIds back to the outcome nodes it was normalized from.
--   • The outcome hierarchy is a DISCOVERY structure — separate from the Section 3 shared legal /
--     factual dependency (EVALUATION) hierarchy. Outcome nodes are NOT independent evidence and are
--     NEVER double-counted in authoritative scoring.
--   • POLOXI Core formulas, the Light Evidence Graph, and the Typed Legal Dependency Graph are
--     UNCHANGED. No new scoring formula, no second engine, no additional LLM call.
--   • Generated by default for LEGAL_DECISION / EVALUATE; NOT forced for IMPLEMENT_DRAFT. General
--     POLOXI Research / Wide (/legal/search) are untouched.
-- The prompt patch is a MINIMAL Section 2 addition + a one-line Section 3 clarification; the output
-- schema gains an OPTIONAL outcomeProposalHierarchy object and candidate originatingOutcomeNodeIds.
-- Idempotent: the prompt/schema UPDATE is guarded by a unique marker; the DDL is IF-guarded.
-- ────────────────────────────────────────────────────────────────────────────────────────────────

-- ── 1) + 2) Patch the DECISION_DISCOVERY_V2 SystemPrompt (Section 2 additive paragraph + Section 3
--    clarification) and extend the OutputSchemaJson (optional outcomeProposalHierarchy object +
--    candidate originatingOutcomeNodeIds). One guarded UPDATE so the whole patch applies exactly once. ──
UPDATE POLOXI.Legal_DecisionPrompt
SET SystemPrompt = REPLACE(
		REPLACE(
			SystemPrompt,
			N'Generate a GLOBAL candidate set of genuinely distinct outcomes responsive to the proposed decisionIntent.',
			N'Generate a GLOBAL candidate set of genuinely distinct outcomes responsive to the proposed decisionIntent. For LEGAL_DECISION / EVALUATE, first propose an outcomeProposalHierarchy representing materially distinct interpretations and prospective outcomes responsive to the decisionIntent. Use L1 for materially distinct outcome interpretations. Use L2/L3+ only where further semantic decomposition identifies a meaningful distinction; do not force a fixed branch count or depth. Preserve stable outcome-node identities, parent-child relationships, descriptions, and the distinction each node represents. Normalize the outcome interpretations into the global candidate set and, on each candidate, preserve explicit originatingOutcomeNodeIds links back to the outcome nodes it was normalized from. Multiple interpretation nodes may normalize to one candidate when they describe the same substantive outcome; materially different outcomes must remain distinct. The outcomeProposalHierarchy is a first-class discovery structure, separate from the shared legal and factual dependency hierarchy. Outcome nodes are not independent evidence supporting their corresponding candidates and must not be double-counted in authoritative scoring. For LEGAL_DECISION / IMPLEMENT_DRAFT, do not force competing outcome branches; follow the drafting objective and its prerequisites.'),
		N'Do NOT use outcome candidates, candidate categories, decision-frame instructions, or generic answer headings as hierarchy branches.',
		N'Do NOT use outcome candidates, candidate categories, decision-frame instructions, or generic answer headings as branches within the shared legal-dependency hierarchy.')
  , OutputSchemaJson = REPLACE(
		REPLACE(
			REPLACE(
				OutputSchemaJson,
